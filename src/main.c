int main(void)
{
	char *str;
	t_node *node;

	signal(SIGINT, acknowledge_sig);
	signal(SIGQUIT, SIG_IGN);
	while(1)
	{
		str = readline("👻>");
		if (!str)
		{
			write(STDOUT_FILENO, "exit\n", 5);
			break ;
		}
		if (ft_strlen(str))
		{
			add_history(str);
			node = get_abstract_syntax_tree(str, 1);
			clean_nodes(&node);
		}
		free(str);
	}
	return (0);
}
